"""Print a self-contained Compose deployment from the files shipped in the image."""

import argparse
from pathlib import Path

import yaml


class _ComposeDumper(yaml.SafeDumper):
    pass


def _represent_string(dumper: yaml.SafeDumper, value: str) -> yaml.ScalarNode:
    return dumper.represent_scalar(
        "tag:yaml.org,2002:str", value, style="|" if "\n" in value else None
    )


_ComposeDumper.add_representer(str, _represent_string)


def render_compose(image: str, source_dir: Path, port: int = 8081) -> str:
    """Use the source stack, replacing local builds and files with image/configs."""
    compose = yaml.safe_load((source_dir / "docker-compose.yml").read_text())
    compose.pop("x-app")
    compose.pop("x-temporal-db")
    services = compose["services"]
    for name in ("web", "worker"):
        services[name]["image"] = image
        services[name].pop("build", None)
    services["web"]["ports"] = [f"${{STONEPEDIA_PORT:-{port}}}:8000"]

    configs = {}
    for service, filename, target in (
        ("temporal-schema", "setup-schema.sh", "/deploy/setup-schema.sh"),
        ("temporal-init", "init.sh", "/deploy/init.sh"),
        (
            "temporal",
            "dynamicconfig.yaml",
            "/etc/temporal/config/dynamicconfig/dynamicconfig.yaml",
        ),
    ):
        # Compose interpolates inline config content. Preserve shell variables
        # for the scripts to expand inside their containers instead.
        content = (source_dir / "temporal" / filename).read_text().replace("$", "$$")
        configs[service] = {"content": content}
        services[service].pop("volumes")
        services[service]["configs"] = [{"source": service, "target": target}]
    compose["configs"] = configs
    return "# Generated by Stonepedia; requires Docker Compose 2.23.1+.\n" + yaml.dump(
        compose, Dumper=_ComposeDumper, sort_keys=False
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--image", required=True, help="Published image name and tag")
    parser.add_argument("--port", type=int, default=8081, help="Default host port (8081)")
    args = parser.parse_args()
    if not 1 <= args.port <= 65535:
        parser.error("--port must be between 1 and 65535")
    print(render_compose(args.image, Path("/app/deploy"), args.port), end="")


if __name__ == "__main__":
    main()
